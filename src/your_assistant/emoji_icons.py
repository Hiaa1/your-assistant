def _svg(*parts: str) -> str:
    return (
        '<svg viewBox="0 0 16 16" width="14" height="14" shape-rendering="crispEdges">'
        + "".join(parts)
        + "</svg>"
    )


def _r(x: int, y: int, w: int, h: int, c: str) -> str:
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{c}"/>'


